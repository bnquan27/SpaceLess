CREATE FUNCTION check_channel_room_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    -- An unchanged legacy name must not block writes such as sending a message.
    IF TG_OP = 'UPDATE' THEN
        IF NEW.name IS NOT DISTINCT FROM OLD.name THEN
            RETURN NEW;
        END IF;
    END IF;
    IF char_length(NEW.name) NOT BETWEEN 1 AND 100 THEN
        RAISE EXCEPTION 'Invalid channel, category or room name length' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER channel_name_length BEFORE INSERT OR UPDATE OF name ON channels
    FOR EACH ROW EXECUTE FUNCTION check_channel_room_name();
CREATE TRIGGER category_name_length BEFORE INSERT OR UPDATE OF name ON room_categories
    FOR EACH ROW EXECUTE FUNCTION check_channel_room_name();
CREATE TRIGGER room_name_length BEFORE INSERT OR UPDATE OF name ON rooms
    FOR EACH ROW EXECUTE FUNCTION check_channel_room_name();

CREATE TABLE room_moderator_denials (
    room_id bigint REFERENCES rooms(id),
    user_id bigint REFERENCES users(id),
    PRIMARY KEY (room_id, user_id)
);
CREATE INDEX room_moderator_denials_user ON room_moderator_denials (user_id);

CREATE VIEW channel_room_access AS
SELECT r.id AS room_id, cm.user_id,
    cm.role_id IN (1, 2) OR (r.private AND COALESCE(rm.is_room_mod, false)) AS moderate
FROM rooms r
JOIN channels c ON c.id = r.channel_id AND c.is_available
JOIN channel_members cm ON cm.channel_id = c.id
JOIN users u ON u.id = cm.user_id AND u.is_available
LEFT JOIN room_members rm ON rm.room_id = r.id AND rm.user_id = cm.user_id
LEFT JOIN room_moderator_denials denial ON denial.room_id = r.id AND denial.user_id = cm.user_id
WHERE r.is_available AND (
    NOT r.private OR cm.role_id = 1 OR (cm.role_id = 2 AND denial.user_id IS NULL)
    OR (cm.role_id = 3 AND rm.user_id IS NOT NULL)
);
