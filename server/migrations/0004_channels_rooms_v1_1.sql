CREATE OR REPLACE FUNCTION check_channel_creator() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    targets bigint[];
    target bigint;
    expected bigint;
BEGIN
    IF TG_TABLE_NAME = 'channels' THEN
        targets := ARRAY[NEW.id];
    ELSIF TG_OP = 'DELETE' THEN
        targets := ARRAY[OLD.channel_id];
    ELSIF TG_OP = 'UPDATE' AND OLD.channel_id <> NEW.channel_id THEN
        targets := ARRAY[OLD.channel_id, NEW.channel_id];
    ELSE
        targets := ARRAY[NEW.channel_id];
    END IF;
    FOREACH target IN ARRAY targets LOOP
        SELECT creator_id INTO expected FROM channels WHERE id = target;
        IF FOUND AND NOT EXISTS (
            SELECT 1 FROM channel_members
            WHERE channel_id = target AND user_id = expected AND role_id = 1
        ) THEN
            RAISE EXCEPTION 'Channel must have its designated creator' USING ERRCODE = '23514';
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER creator_channel_check AFTER INSERT OR UPDATE ON channels
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_channel_creator();
CREATE CONSTRAINT TRIGGER creator_membership_check AFTER INSERT OR UPDATE OR DELETE ON channel_members
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_channel_creator();

